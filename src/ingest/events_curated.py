    if "--check-urls" in sys.argv:
        bad = check_urls(rows)
        log.info("URL check: %d unique URLs, %d failing: %s", len({r['url'] for r in rows}), len(bad), bad)
    df = write_events(rows, "curated_market_events")
    log.info("curated: %d events (%d credit_event)", len(df), (df.type == "credit_event").sum())


